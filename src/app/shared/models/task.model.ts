// ============================================================================
// FILE: task.model.ts
// PURPOSE: Defines all TypeScript interfaces, enums, and types for the
//          Task Management Dashboard. Strong typing prevents runtime errors
//          and enables IntelliSense across the entire application.
// ============================================================================

/**
 * TaskStatus Enum
 * ---------------
 * Represents the lifecycle stages of a task.
 */
export enum TaskStatus {
  PENDING = 'PENDING',
  IN_PROGRESS = 'IN_PROGRESS',
  COMPLETED = 'COMPLETED',
}

/**
 * TaskPriority Enum
 * -----------------
 * Defines urgency levels. Used to sort/filter tasks and color-code UI badges.
 */
export enum TaskPriority {
  LOW = 'LOW',
  MEDIUM = 'MEDIUM',
  HIGH = 'HIGH',
}

/**
 * TaskCategory Enum
 * -----------------
 * Functional workspace / domain category of the task.
 */
export enum TaskCategory {
  ENGINEERING = 'Engineering',
  DESIGN = 'Design',
  PRODUCT = 'Product',
  MARKETING = 'Marketing',
  DEVOPS = 'DevOps',
}

/**
 * Task Interface
 * --------------
 * The core domain model. Every task in the system conforms to this shape.
 */
export interface Task {
  /** Unique identifier for the task */
  id: number;

  /** Short, descriptive title (e.g., "Fix login page bug") */
  title: string;

  /** Detailed description of what needs to be done */
  description: string;

  /** Current lifecycle status of the task */
  status: TaskStatus;

  /** Urgency level — used for sorting and visual indicators */
  priority: TaskPriority;

  /** Name of the person responsible for this task */
  assignee: string;

  /** Optional avatar initials or picture for assignee */
  assigneeAvatar?: string;

  /** Category / team domain */
  category?: string;

  /** When the task was first created */
  createdAt: Date;

  /** When the task was last modified */
  updatedAt: Date;

  /** Optional deadline — null means no deadline */
  dueDate: Date | null;
}

/**
 * CreateTaskPayload
 * -----------------
 * Used when creating a new task. Omits fields that are auto-generated:
 *   - `id` → generated by the service
 *   - `createdAt` → set to current timestamp
 *   - `updatedAt` → set to current timestamp
 */
export type CreateTaskPayload = Omit<Task, 'id' | 'createdAt' | 'updatedAt'>;

/**
 * UpdateTaskPayload
 * -----------------
 * Used for partial updates. `Partial<T>` makes every field optional.
 */
export type UpdateTaskPayload = Partial<CreateTaskPayload>;

/**
 * TaskFilter Interface
 * --------------------
 * Represents the current filter state of the task list.
 */
export interface TaskFilter {
  /** Filter by status — 'ALL' shows all statuses */
  status: TaskStatus | 'ALL';

  /** Filter by priority — 'ALL' shows all priorities */
  priority: TaskPriority | 'ALL';

  /** Filter by category — 'ALL' shows all categories */
  category?: string | 'ALL';

  /** Sort field */
  sortBy?: 'dueDate' | 'priority' | 'createdAt' | 'title';

  /** Sort direction */
  sortDirection?: 'asc' | 'desc';

  /** Free-text search — matched against task title or description */
  searchTerm: string;
}

/**
 * TaskStatistics Interface
 * ------------------------
 * Aggregated counts displayed on the dashboard.
 * Computed from the task list — never stored independently.
 */
export interface TaskStatistics {
  /** Total number of tasks */
  total: number;

  /** Tasks with status PENDING */
  pending: number;

  /** Tasks with status IN_PROGRESS */
  inProgress: number;

  /** Tasks with status COMPLETED */
  completed: number;

  /** Percentage of completed tasks (0 to 100) */
  completionRate: number;
}

/**
 * TaskNotification Interface
 * --------------------------
 * Represents a notification message triggered by task actions.
 */
export interface TaskNotification {
  /** Unique notification ID */
  id: number;

  /** Human-readable notification message */
  message: string;

  /** Category that determines visual styling */
  type: 'INFO' | 'SUCCESS' | 'WARNING' | 'ERROR';

  /** When this notification was generated */
  timestamp: Date;

  /** Whether the user has seen/acknowledged this notification */
  read: boolean;
}
